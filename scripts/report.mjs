// Regenerates docs/PLACEHOLDERS.md and docs/IMAGE-CREDITS.md from the content.
// Run: `pnpm report`
import { readdirSync, readFileSync, statSync, writeFileSync, mkdirSync } from "node:fs";
import { join, relative } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const walk = (dir) => readdirSync(dir).flatMap((f) => { const p = join(dir, f); return statSync(p).isDirectory() ? walk(p) : [p]; });
const files = [...walk(join(root, "content")), ...walk(join(root, "components"))].filter((f) => /\.(ts|tsx)$/.test(f) && !f.endsWith("images.ts"));

const byFile = new Map();
for (const f of files) {
  const lines = readFileSync(f, "utf8").split("\n");
  lines.forEach((line, i) => {
    if (/^\s*(\/\/|\*|\/\*)/.test(line)) return; // skip comments
    // A placeholder starts with a capital letter, is not glued to a Tailwind
    // class prefix (e.g. font-[Times,serif]) and is longer than one letter.
    const hits = [...line.matchAll(/\[[A-Z][^\]\[]{1,160}\]/g)]
      .filter((m) => !/[\w-]$/.test(line.slice(0, m.index)) && !m[0].includes("{"))
      .map((m) => m[0]);
    if (!hits.length) return;
    const key = relative(root, f);
    if (!byFile.has(key)) byFile.set(key, []);
    byFile.get(key).push(...hits.map((h) => ({ line: i + 1, text: h })));
  });
}

let md = "# Placeholders to fill before launch\n\nGenerated by `pnpm report` — every `[BRACKET]` still in the content. They render on the site as yellow dashed chips.\n\n";
md += "Also to provide:\n\n- Contact details, address and social links → `content/site.ts` (`siteConfig`)\n- Booking link (Calendly / Cal.com) → `siteConfig.bookingUrl`\n- Form delivery (email / CRM / webhook) → `lib/forms.ts` and `FORMS_WEBHOOK_URL`\n- Team photos (real people only) → `app/[lang]/team/page.tsx`\n- Real case studies (3 to 5) → `content/work.ts`\n- Real product screenshots → `components/interactive/product-mockup.tsx`\n- Before/after screenshots → `components/interactive/before-after.tsx`\n- Motion reel video → `MotionPlayer src` in `app/[lang]/services/creative-studio/page.tsx`\n- Service zones in Cameroon → `components/interactive/cameroon-map.tsx`\n- Legal texts reviewed by a professional → `content/pages/other.ts` (`legal`)\n\n";
let total = 0;
for (const [file, hits] of [...byFile].sort()) {
  md += `## ${file}\n\n`;
  const seen = new Set();
  for (const h of hits) { const k = `${h.line}:${h.text}`; if (seen.has(k)) continue; seen.add(k); md += `- L${h.line}: \`${h.text}\`\n`; total++; }
  md += "\n";
}
md = md.replace("Generated by", `${total} occurrences. Generated by`);

const imgs = JSON.parse(readFileSync(join(root, "content/data/unsplash.json"), "utf8"));
let cr = "# Image credits\n\nAll photos are from [Unsplash](https://unsplash.com) (Unsplash License). They are also credited on the live `/credits` page.\n\n| Key | Photo | Photographer |\n|---|---|---|\n";
for (const [k, v] of Object.entries(imgs)) cr += `| \`${k}\` | [${v.alt.replace(/\|/g, "/")}](${v.pageUrl}) | [${v.photographer}](${v.photographerUrl}) |\n`;

mkdirSync(join(root, "docs"), { recursive: true });
writeFileSync(join(root, "docs/PLACEHOLDERS.md"), md);
writeFileSync(join(root, "docs/IMAGE-CREDITS.md"), cr);
console.log(`placeholders: ${total} · images: ${Object.keys(imgs).length}`);
