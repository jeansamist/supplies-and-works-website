// Builds content/images.ts from content/data/unsplash.json and adds a tiny
// base64 blur-up preview for each photo. Run: `pnpm images` after editing the JSON.
import { readFileSync, writeFileSync } from "node:fs";

const src = new URL("../content/data/unsplash.json", import.meta.url);
const data = JSON.parse(readFileSync(src, "utf8"));

const out = {};
for (const [key, img] of Object.entries(data)) {
  let blur = "";
  try {
    const res = await fetch(`https://images.unsplash.com/${img.id}?w=16&q=40&fm=jpg&blur=20`);
    if (res.ok) blur = `data:image/jpeg;base64,${Buffer.from(await res.arrayBuffer()).toString("base64")}`;
  } catch {}
  out[key] = { id: img.id, alt: img.alt, photographer: img.photographer, photographerUrl: img.photographerUrl, pageUrl: img.pageUrl, blur };
  process.stdout.write(blur ? "." : "x");
}

const body = `// GENERATED by scripts/build-images.mjs from content/data/unsplash.json.
// To swap a photo: edit the JSON (Unsplash "photo-…" id, alt, credit) and run \`pnpm images\`.
// Photographers are credited automatically on /credits.

export type UnsplashImage = {
  /** "photo-1234567890123-abcdef123456". Empty = shows a styled placeholder. */
  id: string;
  alt: string;
  photographer: string;
  photographerUrl: string;
  pageUrl: string;
  /** Tiny base64 JPEG for the blur-up placeholder. */
  blur?: string;
};

export const images = ${JSON.stringify(out, null, 2)} satisfies Record<string, UnsplashImage>;

export type ImageKey = keyof typeof images;
`;
writeFileSync(new URL("../content/images.ts", import.meta.url), body);
console.log("\ncontent/images.ts written");
